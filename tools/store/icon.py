"""App icon (#8, redrawn as table cuts in T40, #81): a 3x3 night sky of square table-cut gems with one lamp star; gem 7
coming down onto its pale numbered cell. One geometry writes all three outputs:

  androidApp/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive icon, 108dp, inside the 66dp safe zone)
  androidApp/src/main/res/drawable/ic_launcher_monochrome.xml  (themed-icon silhouette)
  tools/store/icon.svg                                         (512x512 Play Store icon, felt background)

Run from the repo root: python3 tools/store/icon.py, then render the store PNG (README -> Play Games setup has the
Brave command): brave --headless=new --hide-scrollbars --window-size=512,512 --screenshot=$PWD/tools/store/icon-512.png
"file://$PWD/tools/store/icon.svg".

The gem is the design system's table cut: the face in its color, four bevels (top 24% white, left 9% white, right 14%
black, bottom 24% black) 20% of the gem wide, and the 0.8dp-at-20dp catchlight (4% of the gem) along the table's top.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FELT = "#4F5A52"
BONE = "#E9E4D8"
CELL = 13.23
STEP = 14.135
X0 = 31.75
SKY = [["#2C4586", "#4A68A6", "#F4E3B1"],
       ["#4A68A6", "#7C97C8", "#2C4586"],
       ["#222724", "#2C4586", None]]  # None: the empty cell gem 7 is coming down onto
EMPTY = "#DCD6C8"
NUMBER = "#2B322D"
FALLING = (66.63, 66.63, 10.33)  # x, y, size of the gem coming down
BEVEL = 0.20
CATCHLIGHT = 0.04
OVERLAYS = [("#3DFFFFFF", "top"), ("#17FFFFFF", "left"), ("#24000000", "right"), ("#3D000000", "bottom")]


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def quad(points):
    (a, b), *rest = points
    return f"M{f(a)},{f(b)}" + "".join(f"L{f(x)},{f(y)}" for x, y in rest) + "Z"


def rect(x, y, w, h):
    return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}z"


def gem(x, y, s, color, shadow):
    """(color, path) layers of one table cut with its drop shadow."""
    b = s * BEVEL
    r, d = x + s, y + s
    faces = {
        "top": [(x, y), (r, y), (r - b, y + b), (x + b, y + b)],
        "left": [(x, y), (x + b, y + b), (x + b, d - b), (x, d)],
        "right": [(r, y), (r, d), (r - b, d - b), (r - b, y + b)],
        "bottom": [(x, d), (x + b, d - b), (r - b, d - b), (r, d)],
    }
    layers = [shadow, (color, rect(x, y, s, s))]
    layers += [(c, quad(faces[name])) for c, name in OVERLAYS]
    layers.append(("#61FFFFFF", rect(x + b, y + b, s - 2 * b, s * CATCHLIGHT)))
    return layers


def layers():
    out = []
    for row, colors in enumerate(SKY):
        for col, color in enumerate(colors):
            x, y = X0 + col * STEP, X0 + row * STEP
            if color is None:
                out.append((EMPTY, rect(x, y, CELL, CELL)))
                out.append(("stroke", "M63.81,63.11H66.81L64.81,67.61"))
                continue
            out += gem(x, y, CELL, color, ("#33000000", rect(x, y + 0.5, CELL, CELL)))
    x, y, s = FALLING
    out += gem(x, y, s, "@color/bone", ("#40000000", rect(x, y + 1.4, s, s)))
    return out


def vector(paths, comment):
    body = "\n".join(paths)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/store/icon.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


def foreground():
    paths = []
    for color, d in layers():
        if color == "stroke":
            paths.append(f'''    <path
        android:strokeColor="{NUMBER}"
        android:strokeWidth="0.9"
        android:strokeLineJoin="round"
        android:pathData="{d}" />''')
        else:
            paths.append(f'''    <path
        android:fillColor="{color}"
        android:pathData="{d}" />''')
    return vector(paths, "App icon (#8, T40): a 3x3 night sky of square table-cut gems with one lamp star; gem 7 coming down onto its pale numbered cell; inside the 66dp safe zone.")


def monochrome():
    paths = []
    for row, colors in enumerate(SKY):
        for col, color in enumerate(colors):
            x, y = X0 + col * STEP, X0 + row * STEP
            if color is None:
                paths.append(f'''    <path
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="0.8"
        android:pathData="{rect(x + 0.4, y + 0.4, CELL - 0.8, CELL - 0.8)}" />''')
            else:
                paths.append(f'''    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{rect(x, y, CELL, CELL)}" />''')
    x, y, s = FALLING
    paths.append(f'''    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{rect(x, y, s, s)}" />''')
    return vector(paths, "Themed-icon silhouette of ic_launcher_foreground: the gems filled, the empty cell outlined.")


def svg():
    # The adaptive icon shows the middle 72 of its 108dp; the store icon is that square at 512px.
    parts = []
    for color, d in layers():
        if color == "stroke":
            parts.append(f'<path d="{d}" fill="none" stroke="{NUMBER}" stroke-width="0.9" stroke-linejoin="round"/>')
            continue
        c = BONE if color == "@color/bone" else color
        if len(c) == 9:  # #AARRGGBB -> fill + opacity
            parts.append(f'<path d="{d}" fill="#{c[3:]}" fill-opacity="{int(c[1:3], 16) / 255:.3f}"/>')
        else:
            parts.append(f'<path d="{d}" fill="{c}"/>')
    body = "\n  ".join(parts)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="18 18 72 72">
  <!-- Play Store icon (#8, T40). Generated by tools/store/icon.py; edit that, not this. -->
  <rect x="18" y="18" width="72" height="72" fill="{FELT}"/>
  {body}
</svg>
'''


if __name__ == "__main__":
    res = ROOT / "androidApp/src/main/res/drawable"
    (res / "ic_launcher_foreground.xml").write_text(foreground())
    (res / "ic_launcher_monochrome.xml").write_text(monochrome())
    (ROOT / "tools/store/icon.svg").write_text(svg())
